/**
 * Bộ mã hoá QR Code (ISO/IEC 18004) tối giản, không phụ thuộc thư viện ngoài.
 * Chế độ byte (UTF-8), phiên bản 1–40 tự chọn nhỏ nhất vừa dữ liệu, mức sửa lỗi L/M/Q/H, tự chọn mặt nạ tốt nhất.
 * Thuật toán theo bản tham chiếu công khai của Project Nayuki (MIT), viết lại gọn cho TypeScript.
 *
 *   const m = encodeQr('ABCD-2345', 'M');  // m.size × m.size, m.get(x, y) = true là ô đen
 */
export type EccLevel = 'L' | 'M' | 'Q' | 'H';
const ECC_INDEX: Record<EccLevel, number> = { L: 0, M: 1, Q: 2, H: 3 };
/** Bit định dạng của mức sửa lỗi (L=1, M=0, Q=3, H=2). */
const ECC_FORMAT_BITS: Record<EccLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

// prettier-ignore
